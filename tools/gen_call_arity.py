#!/usr/bin/env python3
"""Generate src/libbox64_call_arity.inc -- fixed-arity guest call entries.

Why generated: each entry point must have a real C parameter list, so the host
compiler materialises the arguments directly (no varargs, no fmt re-parse, no
per-call marshalling loop).  Seven near-identical functions invite drift when
hand-written, so this script is the single source of truth; the file it emits
is checked in, so a build never needs Python to succeed.

Register order is the SysV64 integer argument order used by the engine's
register file (see include/libbox64.h and unilib/src/abi.h):

    gpr position 0..5  ->  rdi, rsi, rdx, rcx, r8, r9   (_DI.._R9)

The SSE group and the outgoing stack are deliberately never touched: an
all-integer call pays for exactly the argument registers it uses.  The entries
enter through DynaCall_abi(), the known-ABI variant of DynaCall(): a normal
return restores RSP/RIP/eflags and the deferred-flag state exactly as the
generic entry does, but does not re-restore RBX/RBP (non-volatile in both
conventions, so a conforming callee restored the caller's values) nor the
RDI/RSI group (volatile in SysV64, so their post-call values are the callee's
and are never read back; non-volatile and callee-restored in Win64).
Reentrancy, TLS and the longjmp rule stay exactly the engine's.

Regenerate with:  python3 tools/gen_call_arity.py
"""
import os

# Engine register-file positions for SysV64 integer arguments 0..5.
REGS = ["_DI", "_SI", "_DX", "_CX", "_R8", "_R9"]
MAX_ARITY = 6

HEADER = """\
/* Generated by tools/gen_call_arity.py -- DO NOT EDIT.
 *
 * Fixed-arity guest call entries for SysV64 INTEGER/POINTER arguments only
 * (gpr positions 0..5).  Each entry writes exactly the argument registers it
 * needs and then enters through DynaCall_abi(), the known-ABI variant of
 * DynaCall().  The SSE register group and the outgoing stack are never
 * touched, so a call with no floating-point and no stack arguments copies no
 * FPRs and builds no stack blob.  Contract (include/libbox64.h): same 0/error
 * ambiguity and error-slot behaviour; RSP/RIP/eflags/deferred flags and the
 * longjmp rule are DynaCall's, while the RBX/RBP/RDI/RSI re-restore is dropped
 * because `sym` must be a compiled function of the convention the arguments
 * are placed in: RBX/RBP are non-volatile there, and RDI/RSI are either
 * volatile (SysV64) or non-volatile (Win64).
 *
 * Signal-policy scope is selected centrally in DynaCallCore() from the target
 * address, so these entries carry no per-entry policy bookkeeping.
 *
 * Regenerate with:  python3 tools/gen_call_arity.py
 */
"""


def emit(n: int) -> str:
    params = "".join(", uint64_t a%d" % i for i in range(n))
    out = []
    out.append("BOX64_API uint64_t box64_call%d(void* sym%s) {" % (n, params))
    out.append('  x64emu_t* emu = call_entry("box64_call%d", sym);' % n)
    out.append("  uint64_t old_rsp;")
    out.append("  uintptr_t old_ip;")
    out.append("  if (!emu) return 0;")
    out.append("  R_RAX = 0; /* SysV64 varargs: AL = vector registers used */")
    for i in range(n):
        out.append("  emu->regs[%s].q[0] = a%d;" % (REGS[i], i))
    out.append("  /* Align the outgoing RSP for the ABI entry parity; needed for a")
    out.append("   * re-entrant call from a bridge callback too. */")
    out.append("  old_rsp = call_align(emu);")
    out.append("  old_ip = R_RIP;")
    out.append("  DynaCall_abi(emu, (uintptr_t)sym, 0);")
    out.append("  call_unwind(emu, old_rsp, old_ip);")
    out.append("  return call_finish(emu);")
    out.append("}")
    return "\n".join(out)


def main() -> int:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    dest = os.path.join(root, "src", "libbox64_call_arity.inc")
    chunks = [HEADER]
    for n in range(MAX_ARITY + 1):
        chunks.append(emit(n))
    text = "\n".join(chunks) + "\n"

    # Write only on change so an unchanged regeneration does not force a
    # rebuild of the translation unit that includes this file.
    if os.path.exists(dest):
        with open(dest, "r", encoding="utf-8") as f:
            if f.read() == text:
                print("up to date:", dest)
                return 0
    with open(dest, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote:", dest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
